  const canvasPicks = await page.evaluate(async () => {
    const {useStore} = await import('/src/state/store.ts')
    const scene = window.__scanruler.scene()
    const r = document.querySelector('.viewport canvas').getBoundingClientRect()
    return useStore.getState().elements.map(({fit}) => {
      const p = scene.camera.position.clone().set(...fit.center)
      // Stay away from the center pin; this is a click on the fitted surface.
      p.addScaledVector(p.clone().set(...fit.basisU), fit.extentU * .2)
      p.project(scene.camera)
      return [r.x + (p.x + 1) * r.width / 2, r.y + (1 - p.y) * r.height / 2]
    })
  })
  await page.mouse.click(...canvasPicks[0]);await pause(150)
