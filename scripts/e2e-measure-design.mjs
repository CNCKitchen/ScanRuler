// Exercise the redesigned shell through real controls. Store reads only verify
// results; no geometry, drafts or selection are seeded behind the interface.
import assert from 'node:assert/strict'
import puppeteer from 'puppeteer-core'
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { CHROME, APP_URL, OUT_DIR, fieldSetter } from './e2e-lib.mjs'
const out = join(OUT_DIR, 'measure-design')
mkdirSync(out, {recursive:true})
const browser = await puppeteer.launch({executablePath:CHROME,headless:true,defaultViewport:{width:1440,height:900}})
const page = await browser.newPage()
const errors=[]
page.on('pageerror',e=>errors.push(e.message))
const pause = ms=>new Promise(r=>setTimeout(r,ms))
const click = async selector=>{await page.waitForSelector(selector,{visible:true});await page.click(selector);await pause(150)}
const read = fn=>page.evaluate(async source=>{const s=(await import('/src/state/store.ts')).useStore.getState();return (new Function('s',`return (${source})(s)`))(s)},fn.toString())
const record=[]
const check=(condition,label)=>{assert.ok(condition,label);record.push(label);console.log('PASS:',label)}
const screenshot=name=>page.screenshot({path:join(out,`${name}.png`)})
async function rect(selector){return page.$eval(selector,el=>{const r=el.getBoundingClientRect();return{x:r.x,y:r.y,w:r.width,h:r.height}})}
async function fitPlane(x,y){
  await click('[data-test=fit-plane]')
  const r=await rect('.viewport canvas')
  await page.mouse.click(r.x+r.w*x,r.y+r.h*y)
  await page.waitForFunction(()=>document.querySelector('[data-test=create-element]')?.disabled===false)
  await click('[data-test=create-element]');await page.keyboard.press('Escape');await pause(150)
}
async function noOverflow(label){check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),label)}
