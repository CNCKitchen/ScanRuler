  await page.keyboard.press('Enter')
  check(await read(s=>s.draft===null),'unavailable search command cannot start a draft')
  await page.keyboard.press('Escape')
  await click('[data-test=open-measure-sample]')
  await page.waitForFunction(()=>/3,072 triangles/.test(document.querySelector('.file-info')?.textContent??''))
  check(await read(s=>s.fileName==='measurement-sample-30x20x12mm.obj' && s.triangleCount===3072),'sample loads through the real import pipeline')
  const stage=await rect('.stage')
  check(stage.w*stage.h/(1440*900)>=.70,'canvas occupies at least 70% of desktop with context closed')
  await noOverflow('desktop has no page overflow')
  await screenshot('sample-before-fitting')
  await fitPlane(.5,.42)
