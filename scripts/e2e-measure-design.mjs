  check(await read(s=>s.elements[0].name==='Top datum'),'F2 renames without changing geometry')
  check(await page.evaluate(()=>document.activeElement?.getAttribute('role')==='treeitem'),'rename returns focus to the tree')
  await click('[data-test=undo]');check(await read(s=>s.elements[0].name!=='Top datum'),'rename is undoable')
  await click('[data-test=redo]');check(await read(s=>s.elements[0].name==='Top datum'),'rename is redoable')
