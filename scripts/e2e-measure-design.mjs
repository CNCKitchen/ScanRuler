  await page.goto(APP_URL,{waitUntil:'networkidle0'})
  await page.waitForSelector('[data-test=start-pane]')
  await screenshot('01-desktop-start')
  await click('[data-test=measure-search]')
  await page.type('.measure-search input','hole')
