  check(await read(s=>JSON.stringify(s.draft))===draftBefore,'closing Export preserves the exact unfinished draft')
  await click('[data-test=measure-search]')
  await page.keyboard.press('Escape')
  check(await read(s=>JSON.stringify(s.draft))===draftBefore,'closing search preserves the exact unfinished draft')
  await click('[aria-label="Hide Edit element"]')
  await click('.measure-actions .primary')
  check(await read(s=>JSON.stringify(s.draft))===draftBefore,'hide and reopen preserves typed precision and draft')
  await screenshot('02-desktop-edit')
  await click('[data-test=create-element]')
